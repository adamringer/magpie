"""GPS L1 C/A codes (IS-GPS-200 G2 phase-selector taps), as +1/-1 arrays of 1023 chips."""
import numpy as np

_TAPS = {1: (2, 6), 2: (3, 7), 3: (4, 8), 4: (5, 9), 5: (1, 9), 6: (2, 10), 7: (1, 8), 8: (2, 9), 9: (3, 10),
         10: (2, 3), 11: (3, 4), 12: (5, 6), 13: (6, 7), 14: (7, 8), 15: (8, 9), 16: (9, 10), 17: (1, 4),
         18: (2, 5), 19: (3, 6), 20: (4, 7), 21: (5, 8), 22: (6, 9), 23: (1, 3), 24: (4, 6), 25: (5, 7),
         26: (6, 8), 27: (7, 9), 28: (8, 10), 29: (1, 6), 30: (2, 7), 31: (3, 8), 32: (4, 9)}
_cache = {}


def ca(prn):
    if prn not in _cache:
        t0, t1 = _TAPS[prn]
        g1 = [1] * 10
        g2 = [1] * 10
        out = np.empty(1023, np.int8)
        for i in range(1023):
            out[i] = g1[9] ^ g2[t0 - 1] ^ g2[t1 - 1]
            f1 = g1[2] ^ g1[9]
            f2 = g2[1] ^ g2[2] ^ g2[5] ^ g2[7] ^ g2[8] ^ g2[9]
            g1 = [f1] + g1[:9]
            g2 = [f2] + g2[:9]
        _cache[prn] = 1 - 2 * out.astype(float)
    return _cache[prn]
